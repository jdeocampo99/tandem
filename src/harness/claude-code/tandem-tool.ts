import { join } from "node:path";
import { z } from "zod/v4";
import { TANDEM_TOOL_DESCRIPTION, tandemRequestSchema } from "../../session/tools.ts";

/** The generated copy the mod registers; a mod cannot import zod or anything outside its plugin. */
export const TANDEM_TOOL_MODULE = join(
  import.meta.dir,
  "plugins",
  "tandem",
  "hooks",
  "tandem-tool.ts",
);

/** The `tandem` tool as `$.tool.register` takes it, from the schema the sidecar parses with. */
export function tandemToolSpec(): Readonly<{
  name: "tandem";
  description: string;
  inputSchema: Readonly<Record<string, unknown>>;
}> {
  const { $schema: _dialect, ...inputSchema } = z.toJSONSchema(tandemRequestSchema, {
    io: "input",
  });
  return { name: "tandem", description: TANDEM_TOOL_DESCRIPTION, inputSchema };
}

if (import.meta.main) {
  await Bun.write(
    TANDEM_TOOL_MODULE,
    `// Generated by \`bun src/harness/claude-code/tandem-tool.ts\` from src/session/tools.ts; do not edit.\n\nexport const TANDEM_TOOL = ${JSON.stringify(tandemToolSpec(), null, 2)} as const;\n`,
  );
  Bun.spawnSync(["bunx", "biome", "format", "--write", TANDEM_TOOL_MODULE], { stdout: "ignore" });
}
